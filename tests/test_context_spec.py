"""文脈付き辞書（前後の条件）の仕様を固定するテスト。python tests/test_context_spec.py

辞書が育っても結果が変わらないように、当たり方と優先順位をここで決めておく:
  1. YMM4側が長い項目（最長一致）
  2. 前後両方の条件 → 片側だけの条件 → 条件なし
  3. 同じ段なら、前後の条件に含まれる仮名の合計文字数が多い方（記号は数えない）
  4. それでも同じなら、辞書の保存順（YMM4側・前・後の並び。登録した順番には左右されない）
条件は意味を解析しない。記号（' / , + ; _）を除いた前後の仮名の並びが一致したときだけ当てる。
句読点（、。？）と改行はまたがない。
"""
import sys, os, itertools
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from accent_core import Dictionary

n = 0
def case(name, entries, text, want):
    """entries を、登録する順番をすべて入れ替えて試し、どの順番でも同じ結果になることを確かめる"""
    global n
    for order in itertools.permutations(entries):
        d = Dictionary()
        for src, dst, before, after in order:
            d.upsert(src, dst, before=before, after=after)
        got = d.apply(text)[0]
        assert got == want, f"[{name}] 順番 {[o[1] for o in order]}\n got: {got}\nwant: {want}"
    n += 1

E = lambda dst, before="", after="": ("わ", dst, before, after)   # 対象語は「わ」で統一（置き換え後で見分ける）

# ── 当たるか当たらないか ──
case("条件なしだけ",           [E("わ1")], "これわ", "これわ1")
case("前条件が一致",           [E("わ1", before="これ")], "これわ", "これわ1")
case("後条件が一致",           [E("わ1", after="ほん")], "わほん", "わ1ほん")
case("前後両方が一致",         [E("わ1", "これ", "ほん")], "これわほん", "これわ1ほん")
case("片方だけ不一致（前）",   [E("わ1", "これ", "ほん")], "それわほん", "それわほん")
case("片方だけ不一致（後）",   [E("わ1", "これ", "ほん")], "これわいぬ", "これわいぬ")
case("句点の直前（後条件「。」で文末を指定できる）", [E("わ1", after="。")], "これわ。", "これわ1。")
case("句点をまたいで前を見ない",                     [E("わ1", before="これ")], "これ。わ", "これ。わ")
case("句点の直後（前条件「。」で文頭を指定できる）", [E("わ1", before="。")], "これ。わ", "これ。わ1")
case("改行をまたがない",       [E("わ1", before="これ")], "これ\nわ", "これ\nわ")
case("アクセント記号を含む前後（本文側）",   [E("わ1", "これ", "ほん")], "こ'れわほ'ん", "こ'れわ1ほ'ん")
case("アクセント記号を含む前後（条件側）",   [E("わ1", "こ'れ", "ほ'ん")], "これわほん", "これわ1ほん")
case("区切り記号を含む前後",   [E("わ1", "これ", "ほん")], "これ/わ,ほん", "これ/わ1,ほん")
case("区切り記号を条件に書いても同じ",       [E("わ1", "こ/れ", "")], "これわ", "これわ1")
case("無声化 _ を含む前後",    [E("わ1", "すと", "きて")], "て_スとわ_キて", "て_スとわ1_キて")

# ── 競合と優先順位 ──
case("条件付きと条件なしが競合 → 条件付きが勝つ", [E("わ0"), E("わ1", before="これ")], "これわ", "これわ1")
case("条件付きが当たらなければ条件なし",           [E("わ0"), E("わ1", before="これ")], "それわ", "それわ0")
case("前後両方・前だけ・後だけ・条件なしが全部一致 → 前後両方",
     [E("わ0"), E("わB", before="これ"), E("わA", after="ほん"), E("わ2", "これ", "ほん")], "これわほん", "これわ2ほん")
case("片側だけ同士・条件なし → 片側（同じ長さなら保存順＝前「」の方＝後条件の項目）",
     [E("わ0"), E("わB", before="これ"), E("わA", after="ほん")], "これわほん", "これわAほん")
case("前条件「たいよう」と「たいようけい」が両方一致 → 長い方",
     [E("わ4", before="たいよう"), E("わ6", before="たいようけい")], "たいようけいわ", "たいようけいわ6")
case("条件の長さは記号を除いて比べる（「け/い」は2文字）",
     [E("わ2", before="け/い"), E("わ3", before="うけい")], "たいようけいわ", "たいようけいわ3")
case("YMM4側が長い項目は、条件より先（最長一致）",
     [("わ", "わ1", "これ", ""), ("わほん", "わほん0", "", "")], "これわほん", "これわほん0")
case("同じ段（前後両方）では、前後の仮名の合計で比べる：前10＋後1(11) より 前5＋後7(12)",
     [E("わ11", "あいうえおかきくけこ", "さ"), E("わ12", "かきくけこ", "さしすせそたち")],
     "あいうえおかきくけこわさしすせそたち", "あいうえおかきくけこわ12さしすせそたち")
case("長い条件なしの項目は、短い文脈付きの項目より先（はしを ＞ はし＋後「をわたる」）",
     [("はしを", "は'しを", "", ""), ("はし", "はし'", "", "をわたる")], "はしを/わたる", "は'しを/わたる")
print(f"{n} 件 OK（どの登録順でも同じ結果）")
